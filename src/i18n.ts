const DICT = { en, fr };

export function useI18n() {
  const { prefs, state } = useStore();
  const lang = prefs.lang;
  const fmt = state.settings.dateFormat;
  const locale = lang === "fr" ? "fr-FR" : "en-GB";

  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      let s: string = DICT[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v)).replace(`%${k}`, String(v));
      return s;
    },
    [lang],
  );

  return useMemo(() => {
    const date = (iso: string, style?: "long") => {
      if (!iso) return "—";
      if (style === "long") {
        const s = new Date(`${iso.slice(0, 10)}T00:00:00`).toLocaleDateString(locale, { weekday: "long", day: "numeric", month: "long", year: "numeric" });
        return s.charAt(0).toUpperCase() + s.slice(1);
      }
      const [y, m, d] = iso.slice(0, 10).split("-");
      return fmt === "ymd" ? `${y}-${m}-${d}` : `${d}/${m}/${y}`;
    };
    const taxOf = (taxId: string) => state.taxRates.find((r) => r.id === taxId);
    return {
      t,
      lang,
      money: fmtMoney,
      date,
      dateTime: (iso: string) => `${date(iso)} ${iso.slice(11, 16)}`,
      pname: (p: { nameFr: string; nameEn: string }) => (lang === "en" && p.nameEn.trim() ? p.nameEn : p.nameFr),
      pdesc: (p: { descFr: string; descEn: string }) => (lang === "en" ? p.descEn || p.descFr : p.descFr || p.descEn),
      taxLabel: (taxId: string, percent?: number) => {
        const r = taxOf(taxId);
        const pct = percent ?? r?.percent ?? 0;
        const name = r ? (lang === "en" ? r.nameEn : r.nameFr) : lang === "en" ? "VAT" : "TVA";
        if (pct === 0) return name;
        return lang === "fr" ? `${name} ${pct} %` : `${name} ${pct}%`;
      },
      statusLabel: (s: Status) =>
        ({
          en: { draft: "Draft", unpaid: "Unpaid", partial: "Partially Paid", paid: "Paid" },
          fr: { draft: "Brouillon", unpaid: "Impayé", partial: "Partiellement payé", paid: "Payé" },
        })[lang][s],
      // Payment methods are data, stored once in French, so they read the same in both languages.
      methodLabel: (m: PayMethod) => ({ cash: "Espèces", cheque: "Chèque", transfer: "Virement" })[m],
      roleLabel: (r: Role) => t(r === "admin" ? "role_admin" : "role_staff"),
    };
  }, [t, lang, locale, fmt, state.taxRates]);
}
